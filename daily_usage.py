"""카테고리별 1일 권장 사용량(1회 사용량 × 1일 횟수).

크롤링 데이터에는 '권장 사용량' 항목이 따로 없어서(별도 확인 결과, 사용방법
텍스트도 카테고리별 10~45%만 정량 표기) 피부과·업계에서 통용되는 값을
기본치로 둔다. 총용량÷7처럼 상품마다 다른 용량을 그대로 나누면 세제품군에
따라 1일 사용량이 20ml 넘게 나오는 등 비현실적인 값이 나오므로, 카테고리별
1일 권장량을 고정해 두고 그 비율만큼 판매가를 나눠 가격을 매긴다.

선스틱·선스프레이_선패치는 ml_engine.NO_DAILY_SPLIT에서 별도 처리(전체
용량·판매가 그대로 표시)하므로 여기엔 없다.

시트팩·코팩·필링_스크럼·패치·페이셜백은 여기 없다. "주 2회" 같은 고정
빈도를 매일 쓰는 것처럼 나눠 파는 게 아니라 상황에 따라 쓰는 제품이라
정규 패키지 슬롯 자체에서 뺐다(package_rules.SLOTS 참고, SOS 기능으로
별도 예정). 이 표나 ml_engine 어느 쪽에도 값을 못 찾는 카테고리는
총용량÷7 같은 임의 추정을 하지 않고 전체 용량·판매가만 보여준다.
"""

# 카테고리: (1회 사용량, 단위, 1일 사용 횟수)
DAILY = {
    "스킨_토너":        (2.0, "ml", 2),
    "로션":             (1.0, "ml", 2),
    "워터_밀크":        (5.0, "ml", 2),
    "크림":             (0.7, "g", 2),
    "클렌징폼_젤":      (2.0, "g", 2),
    "오일_밤":          (2.5, "ml", 1.5),
    "에센스_세럼_엠플": (1.0, "ml", 2),
    "미스트_오일":      (1.5, "ml", 2),
    "선크림":           (1.0, "g", 1),
    "선쿠션":           (0.6, "g", 1),
    "패드":             (1.0, "매", 1),
    "티슈_패드":        (2.0, "매", 1),
    "립_아이리무버":    (0.5, "ml", 1),
}


def daily_amount(category):
    """(1일 사용량, 단위) 또는 상수를 못 둔 카테고리(스킨케어세트 등)면 None."""
    row = DAILY.get(category)
    if not row:
        return None
    per_use, unit, freq = row
    return round(per_use * freq, 3), unit
