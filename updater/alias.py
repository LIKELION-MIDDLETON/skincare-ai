    ("아이소","이소"),
    ("트라이","트리"),
    ("다이메","디메"),("다이프로","디프로"),("다이포타슘","디포타슘"),
    ("다이소듐","디소듐"),("다이스테아","디스테아"),("다이카프","디카프"),
    ("다이글라이콜","디글라이콜"),("다이올","디올"),("다이에틸","디에틸"),
    ("다이부틸","디부틸"),("다이아","디아"),("다이하이드로","디하이드로"),
