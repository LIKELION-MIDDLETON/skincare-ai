def canon_en(s: str) -> str:
    """영문 INCI 정규화"""
    import re as _re
    return _re.sub(r"[^a-z0-9]","",(s or "").lower())

def canon(s: str) -> str:
    s = s.strip()
    for a,b in RULES: s = s.replace(a,b)
    return s
